    pairs = generate(5000)
    out_path = Path("data/texts/mi_ai_training_5000.txt")
    save(pairs, out_path)
    size_kb = out_path.stat().st_size / 1024
    print(f"OK: {len(pairs)} unique pairs, {size_kb:.1f} KB")
    print(f"Saved: {out_path}")
