def generate(target: int = 5000) -> list[tuple[str, str]]:
    """Собирает все категории + перефразировки, перемешивает, режет до target."""
    pairs: list[tuple[str, str]] = []
    pairs.extend(IDENTITY_QA)
    pairs.extend(CAPABILITIES_QA)
    pairs.extend(PROGRAMMING_QA)
    pairs.extend(ML_QA)
    pairs.extend(ALGO_QA)
    pairs.extend(GENERAL_QA)
    pairs.extend(SOCIAL_QA)
    pairs.extend(PROJECTS_QA)

    # Расширяем через перефразировки
    expanded = []
    for q, a in pairs:
        expanded.extend(make_paraphrases(q, a))

    # Если не хватает — генерируем ещё перефразировок случайных пар
    while len(expanded) < target * 2:
        base = random.choice(pairs)
        extra = make_paraphrases(*base, n=10)
        expanded.extend(extra)

    # Уникализуем
    seen = set()
    unique = []
    for q, a in expanded:
        key = (q.strip(), a.strip())
        if key in seen or not q.strip() or not a.strip():
            continue
        seen.add(key)
        unique.append((q.strip(), a.strip()))

    # Перемешиваем
    random.shuffle(unique)
    return unique[:target]


def save(pairs, path: Path):
    """Запись в формате '### Question: ... ### Answer: ...' (формат Mi-AiLab)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for q, a in pairs:
            f.write(f"### Question: {q}\n### Answer: {a}\n\n")


