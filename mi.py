PARAPHRASE_PREFIXES = [
    "", "Пожалуйста, ", "Скажи: ",
    "Не знаешь, ", "А ", "Можешь ответить: ",
]


QUESTION_PREFIXES = [
    "Пожалуйста, {q}", "Скажи, {q}", "Скажи мне {q}",
    "А {q}", "Не знаешь {q}", "Можешь ответить: {q}",
    "Подскажи: {q}", "Помоги разобраться: {q}",
    "Слушай, {q}", "Интересно: {q}",
    "Извини за вопрос, но {q}", "Кстати, {q}",
    "Не подскажешь {q}", "Хочу узнать: {q}",
    "Объясни плиз: {q}", "Помоги понять: {q}",
]


def lowfirst(s: str) -> str:
    return s[0].lower() + s[1:] if s else s


def make_paraphrases(q: str, a: str, n: int = 30) -> list[tuple[str, str]]:
    """Создаёт N вариаций одного и того же Q&A."""
    variants = [(q, a)]
    base = q.rstrip("?.!").strip()
    base_low = lowfirst(base)

    # === Базовые префиксы (работают для ЛЮБОГО вопроса) ===
    for tpl in QUESTION_PREFIXES:
        # Если оригинал заканчивался на «?» — добавим
        suffix = "?" if q.rstrip().endswith("?") else "."
        new_q = tpl.format(q=base_low) + suffix
        variants.append((new_q, a))

    # === Специальные паттерны ===
    if base.lower().startswith("что такое "):
        topic = base[len("Что такое "):].lower()
        candidates = [
            f"Расскажи про {topic}.",
            f"Объясни {topic}.",
            f"Поясни что такое {topic}.",
            f"Дай определение: {topic}.",
            f"Что значит {topic}?",
            f"{topic[0].upper()}{topic[1:]} — это что?",
            f"В чём смысл {topic}?",
            f"Зачем нужен {topic}?",
            f"Опиши {topic}.",
            f"А {topic} — это вообще что?",
            f"Объясни простыми словами что такое {topic}.",
            f"Что подразумевают под {topic}?",
            f"{topic[0].upper()}{topic[1:]}, что это?",
            f"Дай краткое определение {topic}.",
        ]
        for c in candidates:
            variants.append((c, a))

    elif base.lower().startswith("кто такой "):
        person = base[len("Кто такой "):]
        variants.extend([
            (f"Расскажи про {person}.", a),
            (f"Кем был {person}?", a),
            (f"Что ты знаешь про {person}?", a),
            (f"Что известно о {person}?", a),
            (f"Краткая биография {person}?", a),
            (f"Кто это — {person}?", a),
        ])

    elif base.lower().startswith("кто такая "):
        person = base[len("Кто такая "):]
        variants.extend([
            (f"Расскажи про {person}.", a),
            (f"Кем была {person}?", a),
            (f"Что известно о {person}?", a),
            (f"Кто это — {person}?", a),
        ])

    elif base.lower().startswith("где находится"):
        place = base[len("Где находится "):]
        variants.extend([
            (f"Где {place.lower()}?", a),
            (f"Расскажи про {place.lower()}.", a),
            (f"Что такое {place.lower()}?", a),
            (f"{place} — где это?", a),
        ])

    elif base.lower().startswith("какая столица"):
        country = base[len("Какая столица "):]
        variants.extend([
            (f"Столица {country.lower()}?", a),
            (f"Какой главный город в {country.lower()}?", a),
            (f"Главный город {country.lower()}?", a),
        ])

    elif base.lower().startswith("кто написал"):
        work = base[len("Кто написал "):]
        variants.extend([
            (f"Автор {work}?", a),
            (f"Кто автор {work}?", a),
            (f"Кому принадлежит {work}?", a),
        ])

    elif base.lower().startswith("как "):
        # «Как варить рис?» → «Расскажи как варить рис»
        action = base[4:]
        variants.extend([
            (f"Расскажи как {action.lower()}.", a),
            (f"Подскажи как {action.lower()}?", a),
            (f"Как правильно {action.lower()}?", a),
        ])

    elif base.lower().startswith("сколько "):
        rest = base[8:]
        variants.extend([
            (f"Подскажи сколько {rest.lower()}?", a),
            (f"Скажи, сколько {rest.lower()}?", a),
        ])

    elif base.lower().startswith("чем "):
        rest = base[4:]
        variants.extend([
            (f"В чём разница, {rest.lower()}?", a),
            (f"Объясни чем {rest.lower()}?", a),
        ])

    return variants[:n]


