def write_pair(f, q: str, a: str):
    f.write(f"### Question: {q}\n### Answer: {a}\n\n")


all_pairs: list[tuple[str, str]] = []
all_pairs.extend(IDENTITY)
all_pairs.extend(CAPABILITIES)
all_pairs.extend(PROGRAMMING)
all_pairs.extend(ML_QA)
all_pairs.extend(COMMON_QA)
all_pairs.extend(ALGO_QA)
all_pairs.extend(PROJECT_QA)
all_pairs.extend(SNIPPETS_QA)
all_pairs.extend(GENERAL_QA)


# Дополняем до 5000 через паттерн «уточняющие» вопросы поверх существующих
def make_followup(q: str, a: str) -> list[tuple[str, str]]:
    """Создаёт несколько перефразированных вариантов того же Q&A."""
    base = q.rstrip("?.").strip()
    variants = []
    # Со словом «пожалуйста»
    variants.append((f"Пожалуйста, {base.lower()}.", a))
    # С «ты не знаешь»
    variants.append((f"Не знаешь, {base.lower()}?", a))
    # С «слышал ли ты»
    if base.lower().startswith("что такое"):
        topic = base[len("Что такое "):]
        variants.append((f"Слышал про {topic.lower()}?", a))
        variants.append((f"Знаешь что такое {topic.lower()}?", a))
        variants.append((f"А {topic.lower()} — это что?", a))
    return variants


# Расширяем до ~5000
while len(all_pairs) < 5500:
    # Берём случайные существующие пары и делаем варианты
    base_pair = random.choice(all_pairs[:1500])
    new_variants = make_followup(*base_pair)
    all_pairs.extend(new_variants)
    if len(all_pairs) >= 6000:
        break


# Перемешиваем чтобы темы были в разнобой (модель училась обобщать а не запоминать порядок)
random.shuffle(all_pairs)
all_pairs = all_pairs[:5000]


# Записываем
OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    for q, a in all_pairs:
        write_pair(f, q, a)

size_kb = OUT.stat().st_size / 1024
print(f"OK: {len(all_pairs)} pairs, {size_kb:.1f} KB -> {OUT}")
